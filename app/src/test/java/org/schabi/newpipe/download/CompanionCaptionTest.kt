package org.schabi.newpipe.download

import android.app.Application
import android.net.Uri
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotEquals
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.RuntimeEnvironment
import org.robolectric.annotation.Config
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import org.schabi.newpipe.streams.io.StoredDirectoryHelper

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [28], application = Application::class)
class CompanionCaptionTest {
    @get:Rule val temporary = TemporaryFolder()

    @Test
    fun createsUniqueSidecarAndKeepsSubtitleConversion() {
        val context = RuntimeEnvironment.getApplication()
        val folder = temporary.newFolder()
        val directory = StoredDirectoryHelper(context, Uri.fromFile(folder), "video")
        val video = requireNotNull(directory.createFile("Lesson.mp4", "video/mp4"))
        val subtitle = SubtitlesStream.Builder().setContent("https://example.com/caption", true)
            .setMediaFormat(MediaFormat.TTML).setLanguageCode("en").setAutoGenerated(false).build()
        val first = CompanionCaption.prepare(context, video, subtitle)
        val second = CompanionCaption.prepare(context, video, subtitle)
        assertEquals("Lesson.en.srt", first.first.name)
        assertNotEquals(first.first.uri, second.first.uri)
        assertEquals('s', first.second.kind)
        assertEquals(us.shandian.giga.postprocessing.Postprocessing.ALGORITHM_TTML_CONVERTER, first.second.postprocessingName)
        assertEquals("Lesson.mp4", video.name)
    }
}
