package org.schabi.newpipe.download

import android.content.Context
import androidx.test.core.app.ApplicationProvider
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.stream.DeliveryMethod
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.StreamType
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import org.schabi.newpipe.extractor.stream.VideoStream

class VimeoDownloadCatalogTest {
    @Test
    fun hlsVodFallbackExcludesDashAndPrefersProgressiveFilesWhileKeepingCaptions() {
        val context = ApplicationProvider.getApplicationContext<Context>()
        val hls = video("hls", DeliveryMethod.HLS, "master.m3u8")
        val dash = video("dash", DeliveryMethod.DASH, "manifest.mpd")
        val captions = SubtitlesStream.Builder()
            .setContent("https://media.example.invalid/captions.vtt", true)
            .setMediaFormat(MediaFormat.VTT).setLanguageCode("en").setAutoGenerated(false).build()
        val info = StreamInfo(
            ServiceList.Vimeo.serviceId,
            "https://vimeo.com/1236621193",
            "https://vimeo.com/1236621193",
            StreamType.VIDEO_STREAM,
            "1236621193",
            "Vimeo download fixture",
            0
        ).apply {
            duration = 120
            videoStreams = listOf(hls, dash)
            subtitles = listOf(captions)
        }
        val hlsCatalog = DownloadStreamCatalogFactory.create(context, info)
        assertEquals(listOf(hls), hlsCatalog.videoStreams.streamsList)
        assertEquals(DeliveryMethod.HLS, hlsCatalog.videoStreams.streamsList.single().deliveryMethod)
        assertEquals(0, hlsCatalog.audioTracks.size())
        assertEquals(-1, hlsCatalog.muxedAudioFallbackVideoIndex)
        assertEquals(listOf(captions), hlsCatalog.subtitleStreams.streamsList)

        info.videoStreams = listOf(dash)
        val dashCatalog = DownloadStreamCatalogFactory.create(context, info)
        assertTrue(dashCatalog.videoStreams.streamsList.isEmpty())
        assertEquals(0, dashCatalog.audioTracks.size())
        assertEquals(-1, dashCatalog.muxedAudioFallbackVideoIndex)
        assertEquals(listOf(captions), dashCatalog.subtitleStreams.streamsList)

        val progressive = video("progressive", DeliveryMethod.PROGRESSIVE_HTTP, "video.mp4")
        info.videoStreams = listOf(hls, dash, progressive)
        val progressiveCatalog = DownloadStreamCatalogFactory.create(context, info)
        assertEquals(listOf(progressive), progressiveCatalog.videoStreams.streamsList)
        assertEquals(0, progressiveCatalog.muxedAudioFallbackVideoIndex)
        assertEquals(1, progressiveCatalog.audioTracks.size())
        assertEquals(listOf(captions), progressiveCatalog.subtitleStreams.streamsList)
    }

    private fun video(id: String, delivery: DeliveryMethod, path: String): VideoStream = VideoStream.Builder()
        .setId(id).setContent("https://media.example.invalid/$path", true)
        .setDeliveryMethod(delivery).setMediaFormat(MediaFormat.MPEG_4)
        .setIsVideoOnly(false).setResolution("720p").build()
}
